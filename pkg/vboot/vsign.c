/* vsign — sign and verify VerkOS boot payloads with Ed25519.
 *
 * Runs on the build host, not on VerkOS. vboot verifies what this produces, so
 * the two share ed25519.h and nothing else.
 *
 *   vsign keygen  KEYFILE PUBFILE     make a key pair (KEYFILE stays secret)
 *   vsign sign    KEYFILE FILE        write FILE.sig next to FILE
 *   vsign verify  PUBFILE FILE        check FILE against FILE.sig
 *   vsign pubhdr  PUBFILE             print the public key as a C array for vboot
 *
 * A signature is 64 raw bytes; the .sig file holds exactly that.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <fcntl.h>
#include <unistd.h>
#include <sys/stat.h>
#include "ed25519.h"

static unsigned char *slurp(const char *path, size_t *len) {
    int fd = open(path, O_RDONLY);
    if (fd < 0) { perror(path); return NULL; }
    struct stat st;
    if (fstat(fd, &st)) { perror(path); close(fd); return NULL; }
    unsigned char *b = malloc((size_t)st.st_size + 1);
    if (!b) { close(fd); return NULL; }
    size_t got = 0;
    while (got < (size_t)st.st_size) {
        ssize_t n = read(fd, b + got, (size_t)st.st_size - got);
        if (n <= 0) break;
        got += (size_t)n;
    }
    close(fd);
    *len = got;
    return b;
}
static int spit(const char *path, const void *data, size_t len, int mode) {
    int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, mode);
    if (fd < 0) { perror(path); return -1; }
    int ok = write(fd, data, len) == (ssize_t)len;
    close(fd);
    if (!ok) perror(path);
    return ok ? 0 : -1;
}
/* Seed material. /dev/urandom is the right source on the build host; refuse to
 * invent one, because a predictable key is worse than an obvious failure. */
static int random_seed(ed_u8 seed[32]) {
    int fd = open("/dev/urandom", O_RDONLY);
    if (fd < 0) { perror("/dev/urandom"); return -1; }
    int ok = read(fd, seed, 32) == 32;
    close(fd);
    if (!ok) fprintf(stderr, "vsign: could not read 32 random bytes\n");
    return ok ? 0 : -1;
}

int main(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr,
            "usage: vsign keygen KEYFILE PUBFILE | sign KEYFILE FILE\n"
            "             | verify PUBFILE FILE  | pubhdr PUBFILE\n");
        return 1;
    }
    const char *cmd = argv[1];

    if (!strcmp(cmd, "keygen") && argc == 4) {
        ed_u8 seed[32], pub[32];
        if (random_seed(seed)) return 1;
        ed25519_pubkey(pub, seed);
        if (spit(argv[2], seed, 32, 0600)) return 1;      /* secret: owner only */
        if (spit(argv[3], pub, 32, 0644)) return 1;
        printf("wrote %s (private, keep it safe) and %s\n", argv[2], argv[3]);
        return 0;
    }
    if (!strcmp(cmd, "sign") && argc == 4) {
        size_t klen = 0, mlen = 0;
        unsigned char *seed = slurp(argv[2], &klen);
        if (!seed) return 1;
        if (klen < 32) { fprintf(stderr, "vsign: %s is not a 32-byte key\n", argv[2]); return 1; }
        unsigned char *msg = slurp(argv[3], &mlen);
        if (!msg) return 1;
        ed_u8 pub[32], sig[64];
        ed25519_pubkey(pub, seed);
        ed25519_sign(sig, msg, mlen, seed, pub);
        char out[4096];
        snprintf(out, sizeof out, "%s.sig", argv[3]);
        if (spit(out, sig, 64, 0644)) return 1;
        printf("signed %s (%zu bytes) -> %s\n", argv[3], mlen, out);
        return 0;
    }
    if (!strcmp(cmd, "verify") && argc == 4) {
        size_t plen = 0, mlen = 0, slen = 0;
        unsigned char *pub = slurp(argv[2], &plen);
        unsigned char *msg = slurp(argv[3], &mlen);
        if (!pub || !msg) return 1;
        char sp[4096];
        snprintf(sp, sizeof sp, "%s.sig", argv[3]);
        unsigned char *sig = slurp(sp, &slen);
        if (!sig) return 1;
        if (plen < 32 || slen < 64) { fprintf(stderr, "vsign: bad key or signature size\n"); return 1; }
        int rc = ed25519_verify(sig, msg, mlen, pub);
        printf("%s: %s\n", argv[3], rc == 0 ? "signature OK" : "SIGNATURE INVALID");
        return rc == 0 ? 0 : 2;
    }
    if (!strcmp(cmd, "pubhdr") && argc == 3) {
        size_t plen = 0;
        unsigned char *pub = slurp(argv[2], &plen);
        if (!pub || plen < 32) { fprintf(stderr, "vsign: %s is not a public key\n", argv[2]); return 1; }
        printf("/* generated by: vsign pubhdr %s */\n", argv[2]);
        printf("static const unsigned char VBOOT_PUBKEY[32] = {\n   ");
        for (int i = 0; i < 32; i++) {
            printf(" 0x%02x,", pub[i]);
            if (i % 8 == 7 && i != 31) printf("\n   ");
        }
        printf("\n};\n");
        return 0;
    }
    fprintf(stderr, "vsign: unknown command\n");
    return 1;
}
